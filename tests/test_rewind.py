"""切り出し開始点を話題の頭まで巻き戻す。

投稿済み19本のうち18本が発話の途中から始まっていた。信号のピークで切ると
「山の頂上」に着地して、そこへ至る登り（前提）が入らない。

着地の質は3段階ある。どれで着地したかを返すのは、--dry-run で
**目で止められるようにするため。** 「境界」で止まったものは前提が
入っていない可能性が高いので、人が短い区間を選び直す判断材料になる。
"""

from scripts.moments import rewind_to_topic_head


def cues(*pairs) -> list[dict]:
    return [{"t": t, "line": line} for t, line in pairs]


def test_文の途中で始まっていたら文の頭まで戻る():
    c = cues((7.0, "前の話はここで終わります。"),
             (10.0, "それがうまく刺さってる印象です。"),
             (13.0, "ちょっとある推理していいですか?"),
             (16.0, "で、なんでかって言うと"))
    r = rewind_to_topic_head(15.5, c)
    assert (r["start"], r["kind"]) == (13.0, "文頭")


def test_戻った先が相槌ならさらに前まで戻る():
    # ASRは「はい。」「お」のような断片を独立したキューとして吐く。
    # そこで止めると、結局なんの話か分からないまま始まる
    c = cues((10.0, "それがうまく刺さってる印象です。"),
             (13.0, "ちょっとある推理していいですか?"),
             (15.0, "お"),
             (15.5, "はい。"),
             (16.0, "で、なんでかって言うと"))
    assert rewind_to_topic_head(16.2, c)["start"] == 13.0


def test_音の注記だけのキューでは止まらない():
    c = cues((8.0, "そこを聞かせてください。"),
             (10.0, "本気なんですよ。"),
             (12.0, "[笑い]"),
             (14.0, "そんなことないっす。"))
    assert rewind_to_topic_head(12.5, c)["start"] == 10.0


def test_接続詞で始まるキューでは止まらない():
    # 直前が「。」で終わっていても、中身は前の話の続きになる。
    # 「で、なんでかって言うと」から始めたのが今回のコメントの直接の原因
    c = cues((10.0, "それがうまく刺さってる印象です。"),
             (13.0, "ちょっとある推理していいですか?"),
             (16.0, "で、なんでかって言うと"))
    assert rewind_to_topic_head(16.5, c)["start"] == 13.0


def test_相槌を挟んだ接続詞も続きとみなす():
    # ASRは「はい。で、子供にもそうです。」のように相槌と本文を1キューに混ぜる
    c = cues((7.0, "まず前提の話をします。"),
             (10.0, "自分の子供に体験させたいという話でした。"),
             (13.0, "はい。で、子供にもそうです。"))
    assert rewind_to_topic_head(14.0, c)["start"] == 10.0


def test_すでに文の頭に乗っていれば動かない():
    c = cues((10.0, "それがうまく刺さってる印象です。"),
             (13.0, "ちょっとある推理していいですか?"))
    r = rewind_to_topic_head(13.0, c)
    assert (r["start"], r["kind"]) == (13.0, "文頭")


def test_文頭が見つからなければキュー境界まで寄せる():
    # 発話の途中で切るよりはまし。ただし「境界」と申告して人の目に掛ける
    c = cues((6.0, "前の話も句点が来ないまま続いている"),
             (10.0, "ずっと喋り続けていて句点が来ない"),
             (14.0, "まだ喋り続けている"))
    r = rewind_to_topic_head(15.0, c)
    assert (r["start"], r["kind"]) == (14.0, "境界")


def test_max_backを超えるなら諦めて元の位置を返す():
    # 行き過ぎるくらいなら動かないほうがよい。長すぎるショートは完走されない
    c = cues((0.0, "ずっと前の話です。"))
    r = rewind_to_topic_head(31.0, c, max_back=15.0)
    assert (r["start"], r["kind"]) == (31.0, "そのまま")


def test_字幕が無ければ元の位置を返す():
    r = rewind_to_topic_head(100.0, [])
    assert (r["start"], r["kind"]) == (100.0, "そのまま")


def test_区間より前に字幕が無ければ元の位置を返す():
    assert rewind_to_topic_head(5.0, cues((10.0, "あとの話。")))["kind"] == "そのまま"


def test_疑問符や感嘆符も文末として扱う():
    c = cues((8.0, "そこを聞かせてください。"),
             (10.0, "本気ですか!"),
             (12.0, "資料の7ページのこの数字なんですけど"),
             (15.0, "ここが合わないんですよ"))
    assert rewind_to_topic_head(16.0, c)["start"] == 12.0


def test_戻った先の字幕を返す():
    # --dry-run でそのまま出して、変な戻り方を目で止める
    c = cues((10.0, "それがうまく刺さってる印象です。"),
             (13.0, "ちょっとある推理していいですか?"))
    assert rewind_to_topic_head(14.0, c)["line"] == "ちょっとある推理していいですか?"
